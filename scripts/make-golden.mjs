#!/usr/bin/env node
// Regenerate test/golden.json: the hash manifest the determinism gate compares against.
//
// Committed as JSON hashes rather than PNGs on purpose — the asset pack never enters this repo,
// and a hash of a render is a claim we can check without shipping anyone's art.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { findAssetsDir, packRevision } from "../src/assets-dir.js";
import { Catalog } from "../src/engine/catalog.js";
import { SpriteEngine } from "../src/engine/sheet.js";
import { normalizeSelections } from "../src/engine/selection.js";
import { getAllCredits } from "../src/engine/credits.js";
import { GOLDEN_SPECS } from "../test/golden-specs.mjs";

const ASSETS_DIR = findAssetsDir();
if (!ASSETS_DIR) {
  console.error("ERROR: no LPC asset pack found. Run `npm run setup-assets` first.");
  process.exit(1);
}

const pkg = JSON.parse(fs.readFileSync(new URL("../package.json", import.meta.url), "utf8"));
const catalog = new Catalog(ASSETS_DIR);
const engine = new SpriteEngine(catalog);
const revision = packRevision(ASSETS_DIR);

console.log(`asset pack: ${ASSETS_DIR}`);
console.log(`pack revision: ${revision ?? "not a git checkout"}`);
console.log(`catalog: ${catalog.itemsById.size} items, ${catalog.byTypeName.size} groups`);

const renders = {};
for (const spec of GOLDEN_SPECS) {
  // Preflight every name before any hash is written, so a stale itemId fails the run instead of
  // quietly re-baselining one entry.
  let selections;
  try {
    selections = normalizeSelections(catalog, spec.bodyType, spec.selections, spec.colors);
  } catch (e) {
    console.error(`\nERROR: spec "${spec.name}" does not resolve: ${e.message}`);
    process.exit(1);
  }
  const { canvas, warnings } = await engine.renderCharacter({
    bodyType: spec.bodyType,
    selections,
    matchBodyColorEnabled: true,
  });
  const png = canvas.toBuffer("image/png");
  const credits = getAllCredits(catalog, selections, spec.bodyType);
  renders[spec.name] = {
    bodyType: spec.bodyType,
    selections: spec.selections,
    colors: spec.colors,
    proves: spec.proves,
    width: canvas.width,
    height: canvas.height,
    sha256: crypto.createHash("sha256").update(png).digest("hex"),
    pngBytes: png.length,
    warnings: warnings.slice().sort(),
    creditsEntries: credits.length,
  };
  console.log(
    `${spec.name.padEnd(18)} ${canvas.width}x${canvas.height}  ${String(png.length).padStart(7)} B  ` +
      `sha ${renders[spec.name].sha256.slice(0, 12)}…  warnings=${warnings.length} credits=${credits.length}`,
  );
}

const target = path.join(import.meta.dirname, "..", "test", "golden.json");
fs.writeFileSync(
  target,
  `${JSON.stringify(
    {
      "//": "Generated by `npm run golden`. Hashes of canonical renders; do not hand-edit.",
      packRevision: revision,
      serverVersion: pkg.version,
      nodeVersion: process.version,
      renders,
    },
    null,
    2,
  )}\n`,
);
console.log(`\nwrote ${target}`);
